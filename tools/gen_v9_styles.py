"""Generates v9 seed styles from tools/styles_source.json:
* enhance-server/seed_styles.json (+ seed_media/<id>.jpg)   — WITH prompts
* ai_camera/assets/styles/seed_styles.json (+ samples/<id>.jpg) — NO prompts
* ai_camera/lib/services/local_style_prompts.dart — prompts for the key-only
  TEST build (tree-shaken out of release builds)
Sample images are simple illustrated placeholders; replace them with real
looks from the admin panel."""
import json, math, os, random
from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = json.load(open(os.path.join(ROOT, "tools/styles_source.json"), encoding="utf-8"))
SERVER = os.path.join(ROOT, "enhance-server")
APP = os.path.join(ROOT, "ai_camera")

PAL = {
    "germany_street": [(250, 214, 165), (180, 90, 60), (90, 70, 60)],
    "paris_eiffel": [(250, 200, 170), (160, 170, 210), (80, 80, 110)],
    "swiss_alps": [(130, 190, 250), (240, 245, 250), (70, 140, 70)],
    "santorini": [(255, 200, 120), (40, 110, 200), (245, 245, 245)],
    "dubai_skyline": [(250, 150, 90), (90, 60, 120), (20, 20, 50)],
    "black_suit": [(200, 200, 205), (30, 30, 35), (240, 240, 240)],
    "royal_sherwani": [(120, 30, 40), (230, 190, 90), (60, 10, 20)],
    "silk_saree": [(200, 30, 90), (240, 180, 60), (90, 10, 50)],
    "diwali_lights": [(40, 20, 40), (255, 170, 40), (255, 220, 120)],
    "holi_colors": [(255, 80, 150), (60, 200, 120), (255, 210, 40)],
    "studio_headshot": [(120, 125, 130), (70, 72, 78), (200, 200, 200)],
    "rainy_mumbai": [(40, 60, 90), (240, 170, 70), (20, 30, 50)],
}


def font(size):
    for f in ["/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
              "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"]:
        if os.path.exists(f):
            return ImageFont.truetype(f, size)
    return ImageFont.load_default()


def sample(sid, name, w=480, h=640):
    a, b, c = PAL.get(sid, [(90, 90, 90), (150, 150, 150), (40, 40, 40)])
    im = Image.new("RGB", (w, h))
    px = im.load()
    for y in range(h):
        t = y / h
        col = tuple(int(a[i] * (1 - t) + b[i] * t) for i in range(3))
        for x in range(w):
            px[x, y] = col
    d = ImageDraw.Draw(im)
    rnd = random.Random(sid)
    for _ in range(26):  # backdrop shapes
        x, y = rnd.randint(0, w), rnd.randint(0, int(h * 0.7))
        r = rnd.randint(8, 60)
        col = tuple(min(255, int(v * rnd.uniform(0.7, 1.3))) for v in c)
        d.ellipse([x - r, y - r, x + r, y + r], fill=col)
    im = im.filter(ImageFilter.GaussianBlur(6))
    d = ImageDraw.Draw(im)
    # Person silhouette (head + shoulders) to suggest "you in this look".
    cx = w // 2
    d.ellipse([cx - 62, h - 400, cx + 62, h - 260], fill=(225, 180, 150))
    d.rounded_rectangle([cx - 140, h - 250, cx + 140, h + 40], radius=90, fill=c)
    d.rectangle([0, h - 92, w, h], fill=(0, 0, 0))
    f = font(34)
    tw = d.textlength(name, font=f)
    d.text(((w - tw) / 2, h - 70), name, fill=(255, 255, 255), font=f)
    return im


def main():
    os.makedirs(os.path.join(SERVER, "seed_media"), exist_ok=True)
    os.makedirs(os.path.join(APP, "assets/styles/samples"), exist_ok=True)
    server_styles, app_styles = [], []
    for i, s in enumerate(SRC["styles"]):
        img = sample(s["id"], s["name"])
        img.save(os.path.join(SERVER, "seed_media", f"{s['id']}.jpg"), quality=86)
        img.save(os.path.join(APP, "assets/styles/samples", f"{s['id']}.jpg"), quality=86)
        common = {k: s[k] for k in ("id", "name", "category", "credit_cost", "pro_only")}
        common["sort_order"] = i
        server_styles.append({**common, "prompt": s["prompt"], "display_image": f"{s['id']}.jpg"})
        app_styles.append({**common, "image_asset": f"assets/styles/samples/{s['id']}.jpg"})
    json.dump({"categories": SRC["categories"], "styles": server_styles},
              open(os.path.join(SERVER, "seed_styles.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    json.dump({"version": "seed-1", "categories": SRC["categories"], "styles": app_styles},
              open(os.path.join(APP, "assets/styles/seed_styles.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    lines = [
        "// GENERATED by tools/gen_v9_styles.py — do not edit by hand.",
        "//",
        "// Hidden prompts of the bundled seed styles, used ONLY by the key-embedded",
        "// TEST build when no server is configured (LookService local path). Every",
        "// reference is behind `AiConfig.hasEmbeddedKey` (a compile-time constant),",
        "// so release builds tree-shake this map out — verified by grepping the",
        "// release libapp.so. Production prompts live only on the server.",
        "",
        "const Map<String, String> kLocalSeedStylePrompts = {",
    ]
    for s in SRC["styles"]:
        lines.append(f"  '{s['id']}':")
        lines.append("      " + json.dumps(s["prompt"], ensure_ascii=False).replace("'", "\\'").replace('"', "'", 1)[:-1] + "',")
    lines.append("};")
    open(os.path.join(APP, "lib/services/local_style_prompts.dart"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("ok", len(SRC["styles"]))


if __name__ == "__main__":
    main()
